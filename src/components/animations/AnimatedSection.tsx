export function StaggerContainer({ children, className = '', staggerDelay = 0.1 }: AnimatedSectionProps & { staggerDelay?: number }) {
  return (
    <motion.div
      initial="hidden"
      whileInView="visible"
      viewport={{ once: true, margin: '-50px' }}
      variants={{
        hidden: { opacity: 0 },
        visible: {
          opacity: 1,
          transition: {
            staggerChildren: staggerDelay,
          },
        },
      }}
      className={className}
    >
      {children}
    </motion.div>
  )
}

export function StaggerItem({ children, className = '' }: Omit<AnimatedSectionProps, 'delay'>) {
  return (
    <motion.div
      variants={{
        hidden: { opacity: 0, y: 20 },
        visible: { opacity: 1, y: 0, transition: { duration: 0.5, ease: [0.22, 1, 0.36, 1] } },
      }}
      className={className}
    >
      {children}
    </motion.div>
  )
}

export function FloatingElement({ children, className = '', duration = 6 }: AnimatedSectionProps & { duration?: number }) {
  return (
    <motion.div
      animate={{
        y: [-8, 8, -8],
      }}
      transition={{
        duration,
        repeat: Infinity,
        ease: 'easeInOut',
      }}
      className={className}
    >
      {children}
    </motion.div>
  )
}

export function PulseGlow({ children, className = '' }: Omit<AnimatedSectionProps, 'delay'>) {
  return (
    <motion.div
      animate={{
        boxShadow: [
          '0 0 20px rgba(255, 255, 255, 0.1)',
          '0 0 40px rgba(255, 255, 255, 0.2)',
          '0 0 20px rgba(255, 255, 255, 0.1)',
        ],
      }}
      transition={{
        duration: 3,
        repeat: Infinity,
        ease: 'easeInOut',
      }}
      className={className}
    >
      {children}
    </motion.div>
  )
}

